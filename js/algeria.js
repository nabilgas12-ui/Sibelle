function initWilayas() {
  const sel = document.getElementById('wilayaSelect');
  if (!sel) return;
  // If checkout already filled from Supabase (options > 1), skip static list
  if (sel.options.length > 1 && sel.dataset.fromDb === '1') return;
  // Keep static as fallback until DB loads
  if (sel.options.length <= 1) {
    const keys = Object.keys(ALGERIA);
    keys.forEach(w => {
      const opt = document.createElement('option');
      opt.value = w;
      opt.textContent = w;
      sel.appendChild(opt);
    });
  }
}

function onWilayaChange() {
  // Prefer checkout.html handler if defined later; this is fallback
  if (typeof window._checkoutWilayaChange === 'function') {
    return window._checkoutWilayaChange();
  }
  const wilaya = document.getElementById('wilayaSelect').value;
  const commune = document.getElementById('communeSelect');
  if (!commune) return;
  commune.innerHTML = '<option value="">— اختاري البلدية —</option>';
  if (!wilaya || !ALGERIA[wilaya]) return;
  ALGERIA[wilaya].forEach(c => {
    const opt = document.createElement('option');
    opt.value = c;
    opt.textContent = c;
    commune.appendChild(opt);
  });
}

document.addEventListener('DOMContentLoaded', initWilayas);
window.onWilayaChange = onWilayaChange;
